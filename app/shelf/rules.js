// Ekran Görüntüleri ve Pano rafı — saf kurallar (Electron'a bağlı değil).
//
//   - Pano kabul kuralları: gizli içerik (parola yöneticileri) atlanır; tek başına
//     bir web adresi "Bağlantı", içinde adres geçen paragraf "Metin" sayılır.
//   - Saklama: görsel / metin / bağlantı için ayrı ayrı 1, 3, 7, 15 ya da 30 gün.
//     Sabitlenen, bir klasöre konan ya da etiketlenen öğe süre dolunca da kalır.
//     Süresi dolan öğe Çöp Kutusu'na gider; çöpte 30 gün sonra kalıcı silinir.
//   - Arama: metin, başlık, not, etiket, bağlantı başlığı / alan adı, dosya adı.
"use strict";

const SHELVES = Object.freeze(["image", "text", "link"]);
const RETENTION_DAYS = Object.freeze([1, 3, 7, 15, 30]);
const TRASH_DAYS = 30;
const DAY = 86400000;
const MAX_TEXT = 200000;

// macOS (nspasteboard.org) ve Windows'un "panoya geçmişe alma" işaretleri.
const CONCEALED_FORMATS = Object.freeze([
  "org.nspasteboard.ConcealedType",
  "org.nspasteboard.TransientType",
  "org.nspasteboard.AutoGeneratedType",
  "com.agilebits.onepassword",
  "de.petermaurer.TransientPasteboardType",
  "com.typeit4me.clipping",
  "Pasteboard generator type",
  "ExcludeClipboardContentFromMonitorProcessing",
  "Clipboard Viewer Ignore",
  "CanIncludeInClipboardHistory",
  "CanUploadToCloudClipboard",
]);
const FILE_FORMATS = Object.freeze(["public.file-url", "NSFilenamesPboardType", "text/uri-list", "FileNameW", "FileName", "CF_HDROP"]);

const isConcealed = (formats = []) => formats.some((f) => CONCEALED_FORMATS.some((c) => String(f).toLowerCase() === c.toLowerCase()));
const hasFiles = (formats = []) => formats.some((f) => FILE_FORMATS.includes(String(f)));
const hasImageFormat = (formats = []) => formats.some((f) => /^image\//i.test(String(f)) || /^(public\.(png|tiff|jpeg)|PNG|Bitmap|DeviceIndependentBitmap|CF_DIB)$/i.test(String(f)));

/** Metin tek başına bir http(s) adresi mi? */
function isStandaloneUrl(text) {
  const s = String(text || "").trim();
  if (!s || s.length > 2048 || /\s/.test(s)) return false;
  if (!/^https?:\/\//i.test(s)) return false;
  try {
    const u = new URL(s);
    return Boolean(u.hostname) && u.hostname.includes(".") || u.hostname === "localhost";
  } catch { return false; }
}

function domainOf(url) {
  try { return new URL(String(url)).hostname.replace(/^www\./i, ""); } catch { return ""; }
}

/**
 * Pano içeriğinin rafa alınıp alınmayacağı.
 * snapshot: { formats, text, hasImage }  sources: { image, text, link }
 * → { kind: "image" | "text" | "link", text? } | { skip: "concealed" | "files" | "disabled" | "empty" | "toolong" }
 */
function classifyClipboard(snapshot = {}, sources = {}) {
  const formats = Array.isArray(snapshot.formats) ? snapshot.formats : [];
  if (isConcealed(formats)) return { skip: "concealed" };
  // Finder / Gezgin'de kopyalanan dosya: simge görseli de taşır; rafa alınmaz.
  if (hasFiles(formats)) return { skip: "files" };
  const text = typeof snapshot.text === "string" ? snapshot.text : "";
  if (snapshot.hasImage && !text.trim()) return sources.image ? { kind: "image" } : { skip: "disabled" };
  if (!text.trim()) return snapshot.hasImage && sources.image ? { kind: "image" } : { skip: "empty" };
  if (text.length > MAX_TEXT) return { skip: "toolong" };
  if (isStandaloneUrl(text)) return sources.link ? { kind: "link", text: text.trim() } : { skip: "disabled" };
  return sources.text ? { kind: "text", text } : { skip: "disabled" };
}

/** Süre dolsa da kalır mı? */
const isKept = (item) => Boolean(item?.pinned || item?.folderId || (Array.isArray(item?.tags) && item.tags.length));

const clampRetention = (days) => (RETENTION_DAYS.includes(Number(days)) ? Number(days) : 30);

/**
 * Saklama süresi taraması. → { expire: [kimlik] (çöpe), purge: [kimlik] (kalıcı sil) }
 * retention: { image, text, link } (gün)
 */
function sweep(items, retention = {}, now = Date.now()) {
  const expire = [];
  const purge = [];
  for (const item of items || []) {
    if (item.trashedAt) {
      if (now - item.trashedAt > TRASH_DAYS * DAY) purge.push(item.id);
      continue;
    }
    if (isKept(item)) continue;
    const days = clampRetention(retention[item.kind]);
    const last = Math.max(Number(item.copiedAt) || 0, Number(item.createdAt) || 0);
    if (now - last > days * DAY) expire.push(item.id);
  }
  return { expire, purge };
}

/** Türkçe duyarlı, aksan duyarsız küçük harf. */
function fold(s) {
  return String(s || "")
    .replace(/[İI]/g, (c) => (c === "İ" ? "i" : "ı"))
    .toLocaleLowerCase("tr-TR")
    .replace(/ı/g, "i")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");
}

const searchable = (item) => fold([
  item.title, item.note, item.text, item.url, item.linkTitle, item.linkSite, item.domain, item.name, item.ocr, ...(item.tags || []),
].filter(Boolean).join(" \n "));

/** Tüm sözcükler geçmeli (sıra önemsiz). */
function matches(item, query) {
  const words = fold(query).split(/\s+/).filter(Boolean);
  if (!words.length) return true;
  const hay = searchable(item);
  return words.every((w) => {
    if (w.startsWith("#")) return (item.tags || []).some((t) => fold(t) === w.slice(1) || fold(t).startsWith(w.slice(1)));
    return hay.includes(w);
  });
}

/**
 * Liste süzgeci.
 *   scope: "shelf" (raflar: onShelf) | "library" (çöp dışı tümü) | "trash"
 *   kind, folderId ("none" = klasörsüz), tag, pinned, query
 * Sıra: en yeni kopyalanan önce (rafta), kütüphanede sabitlenenler başta.
 */
function filterItems(items, { scope = "library", kind = null, folderId = null, tag = null, pinned = false, query = "" } = {}) {
  const out = (items || []).filter((item) => {
    if (scope === "trash") { if (!item.trashedAt) return false; } else if (item.trashedAt) return false;
    if (scope === "shelf" && !item.onShelf) return false;
    if (kind && item.kind !== kind) return false;
    if (folderId === "none" ? item.folderId : folderId && item.folderId !== folderId) return false;
    if (tag && !(item.tags || []).includes(tag)) return false;
    if (pinned && !item.pinned) return false;
    return matches(item, query);
  });
  const t = (i) => Math.max(Number(i.copiedAt) || 0, Number(i.createdAt) || 0);
  out.sort((a, b) => (scope === "library" && Boolean(b.pinned) - Boolean(a.pinned)) || (scope === "trash" ? b.trashedAt - a.trashedAt : t(b) - t(a)));
  return out;
}

/** Aynı metin / bağlantı yeniden kopyalanınca yeni kart açılmaz: var olan öğe öne alınır. */
function findDuplicate(items, kind, text) {
  const norm = (s) => String(s || "").replace(/\r\n/g, "\n").trim();
  const t = norm(text);
  return (items || []).find((i) => !i.trashedAt && i.kind === kind && norm(i.kind === "link" ? i.url : i.text) === t) || null;
}

/** Raftan kaldırınca seçilecek öğe: aynı sıradaki sonraki, yoksa önceki. */
function nextSelection(list, removedIds, index) {
  const removed = new Set(removedIds);
  const rest = list.filter((i) => !removed.has(i.id));
  if (!rest.length) return null;
  const after = list.slice(index).find((i) => !removed.has(i.id));
  return (after || rest[rest.length - 1]).id;
}

/** Klasör ağacında döngü olmasın: parent, id'nin kendisi ya da altı olamaz. */
function wouldCycle(folders, id, parentId) {
  let p = parentId;
  const byId = new Map((folders || []).map((f) => [f.id, f]));
  for (let guard = 0; p && guard < 100; guard += 1) {
    if (p === id) return true;
    p = byId.get(p)?.parentId || null;
  }
  return false;
}

/** Etiket metni: baştaki #, fazla boşluk temizlenir; en çok 40 karakter. */
const cleanTag = (t) => String(t || "").replace(/^#+/, "").replace(/\s+/g, " ").trim().slice(0, 40);

// Ekran görüntüsü dosya adları (macOS ve Windows dilleri).
const SCREENSHOT_NAME = /^(screenshot|screen shot|ekran resmi|ekran görüntüsü|ekran goruntusu|bildschirmfoto|capture d.écran|captura de pantalla|schermata|istantanea|скриншот|снимок экрана|cleanshot|ekran kaydı|screen recording)/i;
const IMAGE_EXT = /\.(png|jpe?g|heic|heif|gif|webp|tiff?|bmp)$/i;
function isScreenshotFile(name, { screenshotsOnly = true } = {}) {
  const base = String(name || "");
  if (!base || base.startsWith(".") || !IMAGE_EXT.test(base)) return false;
  return screenshotsOnly ? SCREENSHOT_NAME.test(base.normalize("NFC")) : true;
}

module.exports = {
  SHELVES, RETENTION_DAYS, TRASH_DAYS, CONCEALED_FORMATS, isConcealed, hasFiles, hasImageFormat, isStandaloneUrl, domainOf,
  classifyClipboard, isKept, clampRetention, sweep, fold, matches, filterItems, findDuplicate, nextSelection, wouldCycle, cleanTag,
  isScreenshotFile, IMAGE_EXT,
};
